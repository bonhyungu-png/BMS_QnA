# -*- coding: utf-8 -*-
"""안전점검진단_교량편 전체(1.1~1.7)를 한 번에 뽑는다.
2023·2024·2026년 PDF를 절마다 순서대로 처리한다.

절 하나씩 따로 돌리고 싶으면 구축_1.1.py ~ 구축_1.7.py를 개별 실행해도 된다.
이 스크립트는 그 7개를 순서대로 이어 부르는 것과 같다.
"""
import 구축_절

절목록 = [
    ("1.1 관리일반", "1.1", "관리일반", "1.2"),
    ("1.2 현장조사", "1.2", "현장조사", "1.3"),
    ("1.3 재료시험 항목 및 수량", "1.3", "재료시험 항목 및 수량", "1.4"),
    ("1.4 상태평가기준 및 방법", "1.4", "상태평가기준 및 방법", "1.5"),
    ("1.5 안전성평가기준 및 방법", "1.5", "안전성평가기준 및 방법", "1.6"),
    ("1.6 종합평가기준 및 방법", "1.6", "종합평가기준 및 방법", "1.7"),
    ("1.7 보수·보강 방법", "1.7", "보수·보강 방법", None),
]

if __name__ == "__main__":
    실패 = []
    for 절폴더명, 절_상위, 절_설명, 다음_절_상위 in 절목록:
        print(f"\n========== {절_상위} {절_설명} ==========")
        try:
            구축_절.실행(절폴더명, 절_상위, 절_설명, 다음_절_상위)
        except Exception as e:
            print(f"  ! 실패: {type(e).__name__}: {e}")
            실패.append(절_상위)

    print("\n" + "=" * 40)
    if 실패:
        print(f"완료 (실패한 절: {', '.join(실패)})")
    else:
        print("전체 절(1.1~1.7) 완료 — 실패 없음")
